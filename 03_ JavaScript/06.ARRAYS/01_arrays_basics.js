// Arrays basics

let marks = [100, 50, 70, 80, 90];

console.log(marks);
console.log(marks.length);

let arr = [100, 30, "Rohit", true];
console.log(arr);

// push: add at end
arr.push(90);
arr.push("Strike");
console.log(arr);

// pop: remove from end
arr.pop();
console.log(arr);

// unshift: add at start
arr.unshift(10);
arr.unshift(50);
console.log(arr);

// shift: remove from start
arr.shift();
console.log(arr);
