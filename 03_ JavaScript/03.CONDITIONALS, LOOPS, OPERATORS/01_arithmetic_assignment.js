// Arithmetic operators: + - * / % **

console.log(2 + 5);
console.log(2 - 5);
console.log(2 * 5);
console.log(6 / 2);
console.log(5 % 2);   // remainder
console.log(5 ** 3);  // power

// Assignment operators: = += -= *= /= %=

let x = 20;
let y = 10;

x = x + y;
x = x - y;
x = x * y;
x += y;
x %= y;

console.log(x);
