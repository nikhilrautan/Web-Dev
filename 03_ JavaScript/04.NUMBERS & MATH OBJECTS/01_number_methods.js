let b = 345.6821;

// toFixed() returns string
let c = b.toFixed(1);
console.log(c);          // 345.7
console.log(typeof c);   // string

// toPrecision()
console.log(b.toPrecision(4)); // total digits

// toString()
console.log(b.toString());
console.log(typeof b.toString());
